import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('public website, customer registration, isolation, billing and sign out use real Core', async ({ page }) => {
  const errors = []; page.on('pageerror', error => { errors.push(error.message); console.error('Browser error:', error.message); });
  const forbidden = []; page.on('request', request => { if (/9090|docker\.sock|\/containers\//.test(request.url())) forbidden.push(request.url()); });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Build your world/ })).toBeVisible();
  await expect(page.getByLabel('Game or app')).toContainText('Minecraft');
  await page.locator('header').getByRole('button', { name: 'Status', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Service status', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Database', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Provisioning & lifecycle queue', exact: true })).toBeVisible();
  await page.locator('header').getByRole('button', { name: 'My servers', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  await page.getByLabel('Your name').fill('Browser smoke customer');
  await page.getByLabel('Email', { exact: true }).fill(`browser-${randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill(randomUUID());
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My servers', exact: true })).toBeVisible();
  await expect(page.getByText('Create your first server to get started.')).toBeVisible();
  await expect(page.locator('header').getByRole('button', { name: 'Admin', exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'My servers', exact: true })).toBeVisible();
  await page.locator('header').getByRole('button', { name: 'Create server', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'From idea to your own server' })).toBeVisible();
  await page.getByRole('button', { name: /Alpine development workload/ }).click();
  await page.getByRole('button', { name: /Choose your plan/ }).click();
  await page.getByRole('button', { name: /Starter resources/ }).click();
  await page.getByRole('button', { name: /Choose your location/ }).click();
  const serverName = `Browser checkout ${randomUUID()}`;
  await page.getByLabel('Server name', { exact: true }).fill(serverName);
  await page.getByLabel('Hosting location', { exact: true }).selectOption({ label: 'Local Development · Development Node 2' });
  await page.getByRole('button', { name: /Review your order/ }).click();
  await page.getByRole('button', { name: /Create invoice and continue/ }).click();
  await expect(page.getByRole('heading', { name: 'Complete your payment' })).toBeVisible();
  await page.getByRole('button', { name: 'View your invoices', exact: true }).click();
  await page.locator('header').getByRole('button', { name: 'Billing', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Billing sandbox', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Sandbox invoices', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: new RegExp(serverName) })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Simulate payment and provision', exact: true })).toHaveCount(0);
  await page.locator('header').getByRole('button', { name: 'Support', exact: true }).click();
  await page.getByRole('button', { name: 'New ticket', exact: true }).click();
  const subject = `Browser support ${randomUUID()}`;
  await page.getByLabel('Subject', { exact: true }).fill(subject);
  await page.getByLabel('Message', { exact: true }).fill('Please check my test invoice.');
  await page.getByRole('button', { name: 'Submit ticket', exact: true }).click();
  await expect(page.getByRole('heading', { name: subject, exact: true })).toBeVisible();
  await page.getByLabel('Your reply', { exact: true }).fill('Adding test details.');
  await page.getByRole('button', { name: 'Send reply', exact: true }).click();
  await expect(page.getByText('Adding test details.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close ticket', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Reopen ticket', exact: true })).toBeVisible();
  await page.locator('header').getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.locator('header').getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
  await page.locator('header').getByRole('button', { name: 'My servers', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible();
  expect(errors).toEqual([]); expect(forbidden).toEqual([]);
});
