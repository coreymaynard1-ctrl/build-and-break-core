import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';

test('admin node onboarding, coverage and real Minecraft management UI', async ({ page }) => {
  test.skip(!process.env.DATABASE_URL || !process.env.BNB_TEST_MC_SERVICE, 'Requires operator database access and a dedicated Minecraft test service');
  const connection = new URL(process.env.DATABASE_URL);
  const env = { ...process.env, PGHOST: connection.hostname, PGPORT: connection.port || '5432', PGDATABASE: connection.pathname.slice(1), PGUSER: decodeURIComponent(connection.username), PGPASSWORD: decodeURIComponent(connection.password), PGSSLMODE: connection.searchParams.get('sslmode') || 'prefer' };
  const sql = query => execFileSync('psql', ['-X', '-v', 'ON_ERROR_STOP=1', '-c', query], { env, stdio: 'pipe' });
  const errors = []; page.on('pageerror', err => errors.push(err.message));
  const res = await page.request.post('/api/v1/auth/register', { data: { email: `bnb-admin-browser-${randomUUID()}@example.test`, name: 'Temporary admin browser test', password: randomUUID() } });
  expect(res.status()).toBe(200);
  const session = await res.json(); const id = session.user.id;
  expect(id).toMatch(/^[a-f0-9-]{36}$/);
  try {
    sql(`UPDATE accounts SET role='admin' WHERE id='${id}'`);
    await page.goto('/#admin');
    await expect(page.getByRole('heading', { name: 'Administration', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Game & app deployment coverage', exact: true })).toBeVisible();
    await page.getByLabel('Node name', { exact: true }).fill('Browser test node');
    await page.getByLabel('Location', { exact: true }).fill('Test location');
    await page.getByRole('button', { name: 'Create enrollment token', exact: true }).click();
    await expect(page.getByText(/Use this token once on the new host/)).toBeVisible();
    await page.getByRole('button', { name: 'Hide token', exact: true }).click();
    await page.goto(`/#services/${process.env.BNB_TEST_MC_SERVICE}`);
    await expect(page.getByRole('heading', { name: 'Server console', exact: true })).toBeVisible();
    await expect(page.locator('.server-console')).toContainText('Minecraft');
    await expect(page.locator('.server-console')).toHaveAttribute('data-service-id', process.env.BNB_TEST_MC_SERVICE);
    if (process.env.BNB_TEST_SECOND_MC_SERVICE) {
      await page.getByLabel('Minecraft command', { exact: true }).fill('say unsent first-server command');
      await page.goto(`/#services/${process.env.BNB_TEST_SECOND_MC_SERVICE}`);
      await expect(page.locator('.server-console')).toHaveAttribute('data-service-id', process.env.BNB_TEST_SECOND_MC_SERVICE);
      await expect(page.getByLabel('Minecraft command', { exact: true })).toHaveValue('');
      await expect(page.getByText('172.24.50.244:25575', { exact: true }).first()).toBeVisible();
      await page.getByRole('button', { name: 'Startup', exact: true }).click();
      await expect(page.getByRole('heading', { name: 'Startup configuration', exact: true })).toBeVisible();
      await expect(page.getByText('25575', { exact: true })).toBeVisible();
      await expect(page.getByText('25565', { exact: true })).toHaveCount(0);
      await page.goto(`/#services/${process.env.BNB_TEST_MC_SERVICE}`);
      await expect(page.locator('.server-console')).toHaveAttribute('data-service-id', process.env.BNB_TEST_MC_SERVICE);
      await expect(page.getByLabel('Minecraft command', { exact: true })).toHaveValue('');
    }
    await page.getByRole('button', { name: 'Startup', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Startup configuration', exact: true })).toBeVisible();
    await expect(page.getByLabel('Startup command', { exact: true })).toHaveValue(/java /);
    await page.getByLabel('Startup command', { exact: true }).fill('env MY_FLAG=1 {{DEFAULT_COMMAND}}');
    await page.getByRole('button', { name: 'Reset to template default', exact: true }).click();
    await expect(page.getByLabel('Startup command', { exact: true })).toHaveValue(/java /);
    await page.getByRole('button', { name: 'JAR Manager', exact: true }).click();
    await expect(page.getByLabel('Server software', { exact: true })).toHaveValue('PAPER');
    await expect(page.locator('datalist[id^=versions] option[value="1.7.10"]')).toHaveCount(1);
    await expect(page.locator('datalist[id^=versions] option[value="26.3"]')).toHaveCount(1);
    await page.getByRole('button', { name: 'Plugins', exact: true }).click();
    await expect(page.getByRole('heading', { name: /Selected plugins/ })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Remove', exact: true })).toHaveCount(1);
    await page.getByLabel('Search Modrinth', { exact: true }).fill('luckperms');
    const search = page.waitForResponse(r => r.url().includes('/minecraft/catalogue'));
    await page.getByRole('button', { name: 'Search catalogue', exact: true }).click();
    expect((await search).status()).toBe(200);
    await expect(page.getByRole('heading', { name: 'LuckPerms', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'JAR Manager', exact: true }).click();
    await page.getByLabel('Server software', { exact: true }).selectOption('VANILLA');
    await page.getByRole('button', { name: 'Mods', exact: true }).click();
    await expect(page.getByText('Vanilla does not load mods or plugins.', { exact: false })).toBeVisible();
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await expect(page.getByLabel('Server message (MOTD)', { exact: true })).toBeVisible();
    await expect(page.getByLabel('Maximum players', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Files', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Files', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Refresh files', exact: true })).toBeEnabled({ timeout: 30000 });
    await expect(page.locator('tbody')).toContainText('server.properties');
    const file = `.bnb-browser-${randomUUID()}.txt`;
    await page.getByRole('button', { name: 'New text file', exact: true }).click();
    await page.getByLabel('File path', { exact: true }).fill(file);
    await page.getByLabel('File contents', { exact: true }).fill('browser file operation verified');
    await page.getByRole('button', { name: 'Save file', exact: true }).click();
    const row = page.getByRole('row').filter({ hasText: file });
    await expect(row).toBeVisible({ timeout: 30000 });
    await expect(row.getByRole('button', { name: 'Edit', exact: true })).toBeEnabled();
    await row.getByRole('button', { name: 'Edit', exact: true }).click();
    await expect(page.getByLabel('File contents', { exact: true })).toHaveValue('browser file operation verified');
    await expect(row.getByRole('button', { name: 'Delete', exact: true })).toBeEnabled();
    page.once('dialog', dialog => dialog.accept());
    await row.getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(row).toHaveCount(0, { timeout: 30000 });
    expect(errors).toEqual([]);
  } finally {
    sql(`UPDATE accounts SET role='customer',disabled=true WHERE id='${id}'`);
    sql(`DELETE FROM account_sessions WHERE account_id='${id}'`);
  }
});
